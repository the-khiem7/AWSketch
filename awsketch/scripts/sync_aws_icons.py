#!/usr/bin/env python3
"""Import the official AWS Architecture Icons package into awsketch/assets/icons.

Usage: uv run awsketch/scripts/sync_aws_icons.py <package.zip | package-folder>

Takes the 64px service icons (Arch_*_64.svg), the 48px resource icons (Res_*_48.svg) and the group icons (Architecture-Group-Icons/*_32.svg), wraps each as a standalone <svg> (opens in a browser; the renderer turns it into a <symbol>), adds the ones whose id is new to assets/icons/<kind>/<category>/ (group icons have no category), and rewrites index.json and references/icon-catalog.md. Existing icons are never overwritten.
"""
import json
import re
import sys
import zipfile
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
ICONS = SKILL / "assets" / "icons"
CATALOG = SKILL / "references" / "icon-catalog.md"
SVG_NS = 'xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"'

# (path pattern, kind, id prefix, size); the optional "c" group is the package category folder
RULES = [
    (re.compile(r"(^|/)Arch_(?P<c>[^/]+)/64/Arch_(?P<n>[^/]+)_64\.svg$"), "service", "", 64),
    (re.compile(r"(^|/)Res_(?P<c>[^/]+)/Res_(?P<n>[^/]+)_48\.svg$"), "resource", "res-", 48),
    (re.compile(r"(^|/)Res_(?P<c>General-Icons)/Res_48_Light/Res_(?P<n>[^/]+)_48_Light\.svg$"), "resource", "res-", 48),
    (re.compile(r"(^|/)Architecture-Group-Icons[^/]*/(?P<n>[^/]+)_32\.svg$"), "group", "group-", 32),
]


def read_package(source):
    path = Path(source)
    if path.is_dir():
        return {p.relative_to(path).as_posix(): p.read_bytes() for p in path.rglob("*.svg")}
    with zipfile.ZipFile(path) as z:
        return {n: z.read(n) for n in z.namelist() if n.endswith(".svg") and not n.startswith("__MACOSX")}


def wrap(icon_id, svg):
    root = re.search(r"<svg\b[^>]*>", svg)
    view_box = re.search(r'viewBox="([^"]+)"', root.group(0)).group(1)
    inner = svg[root.end():svg.rindex("</svg>")]
    inner = re.sub(r"<(title|desc)>.*?</\1>", "", inner, flags=re.S)
    referenced = set(re.findall(r"url\(#([^)]+)\)", inner)) | set(re.findall(r'href="#([^"]+)"', inner))

    def fix_id(m):
        return f'id="{icon_id}-{m.group(1)}"' if m.group(1) in referenced else ""

    inner = re.sub(r'\s*id="([^"]*)"', lambda m: " " + fix_id(m) if fix_id(m) else "", inner)
    for ref in referenced:
        inner = inner.replace(f"url(#{ref})", f"url(#{icon_id}-{ref})").replace(f'href="#{ref}"', f'href="#{icon_id}-{ref}"')
    inner = re.sub(r">\s+<", "><", inner.strip())
    return view_box, f'<svg {SVG_NS} id="{icon_id}" viewBox="{view_box}">{inner}</svg>\n'


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def classify(name):
    for pattern, kind, prefix, size in RULES:
        m = pattern.search(name)
        if m and "Dark" not in name:
            label = m.group("n")
            category = slug(m.groupdict().get("c") or "")
            return kind, prefix + slug(label), label.replace("_", " ").replace("-", " ").replace("&", "and"), size, category
    return None


def main(source):
    files = read_package(source)
    ICONS.mkdir(parents=True, exist_ok=True)
    index_path = ICONS / "index.json"
    index = json.loads(index_path.read_text(encoding="utf-8")) if index_path.exists() else {}
    index = {k: v for k, v in index.items() if v.get("path") and (ICONS / v["path"]).exists()}
    added = skipped = 0
    for name in sorted(files):
        found = classify(name)
        if not found:
            continue
        kind, icon_id, label, size, category = found
        svg = files[name].decode("utf-8")
        if "<style" in svg:
            print("skip (style block): " + name)
            skipped += 1
            continue
        if icon_id in index:
            continue
        view_box, symbol = wrap(icon_id, svg)
        rel = "/".join(part for part in (kind, category, f"{icon_id}.svg") if part)
        target = ICONS / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(symbol, encoding="utf-8")
        index[icon_id] = {"name": label, "kind": kind, "category": category, "path": rel, "viewBox": view_box, "size": size}
        added += 1
    index = dict(sorted(index.items()))
    index_path.write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    write_catalog(index)
    print(f"added {added} icons, skipped {skipped}, total {len(index)}")


def write_catalog(index):
    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    out = ["# Icon catalog", "", "Generated by `scripts/sync_aws_icons.py` from `assets/icons/index.json`; do not edit by hand. Use the id in a node `icon` field or run `render.py --list-icons`.", ""]
    for kind, title in (("service", "Service icons (64px tiles)"), ("resource", "Resource icons (48px)"), ("group", "Group icons")):
        rows = [(i, e) for i, e in index.items() if e["kind"] == kind]
        out += [f"## {title}", "", "| id | name | category | size |", "|---|---|---|---|"]
        out += [f"| {i} | {e['name']} | {e['category'] or '-'} | {e['size']} |" for i, e in rows]
        out.append("")
    CATALOG.write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
